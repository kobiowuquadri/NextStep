import { writeFileSync } from 'node:fs';
import { themes, cssVariables, radius, space, motion } from '../dist/index.js';

const block = (vars, indent = '  ') =>
  Object.entries(vars)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join('\n');

const shared = {
  '--ns-radius-sm': `${radius.sm}px`,
  '--ns-radius-md': `${radius.md}px`,
  '--ns-radius-lg': `${radius.lg}px`,
  '--ns-radius-xl': `${radius.xl}px`,
  '--ns-radius-pill': `${radius.pill}px`,
  '--ns-motion-fast': `${motion.fast}ms`,
  '--ns-motion-base': `${motion.base}ms`,
  '--ns-motion-slow': `${motion.slow}ms`,
  ...Object.fromEntries(Object.entries(space).map(([k, v]) => [`--ns-space-${k}`, `${v}px`])),
};

const css = [
  '/* Generated by @nextstep/design-tokens. Do not edit by hand. */',
  ':root {',
  block(shared),
  block(cssVariables(themes.light)),
  '  color-scheme: light;',
  '}',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  block(cssVariables(themes.dark), '    '),
  '    color-scheme: dark;',
  '  }',
  '}',
  ':root[data-theme="dark"] {',
  block(cssVariables(themes.dark)),
  '  color-scheme: dark;',
  '}',
  '',
].join('\n');

writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
console.log('tokens.css written');
